"""Regenerate/check docs/catalogue.md, the reference of kinds, units and systems."""

import argparse
from pathlib import Path

from quantype._internal._registry import BASIS
from quantype._internal._semantics import KINDS
from quantype._internal._systems import coherence
from quantype.catalogue import builtin_catalogue
from quantype.codegen._render import unit_names
from quantype.systems import CGS, SI, Atomic, Atomistic, Metal, Real

TARGET = Path(__file__).resolve().parents[1] / "docs/catalogue.md"
SYSTEMS = (Atomistic, Metal, Real, SI, CGS, Atomic)
SUPERSCRIPTS = str.maketrans("-0123456789", "⁻⁰¹²³⁴⁵⁶⁷⁸⁹")
AXES = {"magnetic_moment": "magnetic moment"}

HEADER = """\
<!-- Generated by scripts/generate_docs.py; do not edit. -->
# Kinds and units

Every built-in quantity kind, the units that construct it, the products and
quotients that name their result, and the unit each built-in system stores it
in. Units are flat attributes of `quantype.u`, such as `u.nm`, and also sit in
a namespace per kind, such as `u.length.nanometer`. Dimensions are over
quantype's base axes: {axes}.
"""


def _dimensions(exponents: tuple[int, ...]) -> str:
    def term(axis: str, power: int) -> str:
        name = AXES.get(axis, axis)
        return name if power == 1 else f"{name}{str(power).translate(SUPERSCRIPTS)}"

    pairs = list(zip(BASIS, exponents, strict=True))
    numerator = " ".join(term(axis, power) for axis, power in pairs if power > 0)
    denominator = " ".join(term(axis, -power) for axis, power in pairs if power < 0)
    if not denominator:
        return numerator or "dimensionless"
    return f"{numerator or '1'} / {denominator}"


def _kinds() -> str:
    catalogue = builtin_catalogue()
    identifiers: dict[str, list[str]] = {}
    for identifier, name in unit_names(catalogue).items():
        identifiers.setdefault(name, []).append(identifier)
    rows = ["| Kind | Dimensions | Units |", "| --- | --- | --- |"]
    for kind, spec in catalogue.quantities.items():
        units = [
            f"`{name}` ({unit.symbol or name})"
            + "".join(
                f", `{alias}`" for alias in identifiers.get(name, []) if alias != name
            )
            for name, unit in catalogue.units.items()
            if unit.kind == kind
        ]
        rows.append(
            f"| `{kind}` | {_dimensions(spec.dimensions)} | {'; '.join(units)} |"
        )
    return "\n".join(rows)


def _relations() -> str:
    algebra = builtin_catalogue().algebra
    products: set[str] = set()
    quotients: list[str] = []
    for (operation, left, right), result in sorted(algebra.items()):
        if "Dimensionless" in (left, right) and result != "Dimensionless":
            continue  # scaling by a dimensionless value keeps the kind
        if operation == "mul":
            first, second = sorted((left, right))
            products.add(f"`{first}` \N{MULTIPLICATION SIGN} `{second}` = `{result}`")
        elif left != right:
            quotients.append(f"`{left}` / `{right}` = `{result}`")
    return (
        "Each product also names the quotients that undo it. Anything else stays "
        "an unnamed (structural) quantity, which `Kind.reinterpret(q)` can name.\n\n"
        "**Products**\n\n"
        + "\n".join(f"- {line}" for line in sorted(products))
        + "\n\n**Quotients**\n\n"
        + "\n".join(f"- {line}" for line in quotients)
    )


def _systems() -> str:
    names = " | ".join(f"`{system.__name__}`" for system in SYSTEMS)
    rows = [
        f"| Kind | {names} |",
        "| --- |" + " --- |" * len(SYSTEMS),
    ]
    for name, kind in KINDS.items():
        cells = []
        for system in SYSTEMS:
            symbol = system.unit_for(kind).symbol
            # A starred unit is stored outside the base units' coherent products.
            cells.append(f"{symbol}*" if coherence(system, kind) != 1.0 else symbol)
        rows.append(f"| `{name}` | " + " | ".join(cells) + " |")
    return (
        "`System.unit_for(Kind)` gives these units; `.value` is in them. A star marks "
        "a unit the system stores outside its base units' coherent products, as "
        "LAMMPS does; arithmetic producing or consuming those kinds rescales.\n\n"
        + "\n".join(rows)
    )


def render() -> str:
    axes = ", ".join(AXES.get(axis, axis) for axis in BASIS)
    return (
        HEADER.format(axes=axes)
        + "\n## Kinds\n\n"
        + _kinds()
        + "\n\n## Named products and quotients\n\n"
        + _relations()
        + "\n\n## Units by system\n\n"
        + _systems()
        + "\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != source:
            parser.exit(1, f"Stale generated file: {TARGET}\n")
        return
    TARGET.write_text(source)


if __name__ == "__main__":
    main()
