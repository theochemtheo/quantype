"""Regenerate/check docs/reference/catalogue.md: kinds, units, and systems."""

import argparse
from pathlib import Path

from quantype._internal._registry import BASIS
from quantype._internal._semantics import KINDS
from quantype._internal._systems import coherence
from quantype.catalogue import builtin_catalogue
from quantype.codegen._render import unit_names
from quantype.codegen._table import named_power
from quantype.systems import ASE, CGS, SI, Atomic, Atomistic, Metal, Real

TARGET = Path(__file__).resolve().parents[1] / "docs/reference/catalogue.md"
SYSTEMS = (Atomistic, ASE, Metal, Real, SI, CGS, Atomic)
SUPERSCRIPTS = str.maketrans("-0123456789", "⁻⁰¹²³⁴⁵⁶⁷⁸⁹")
AXES = {"magnetic_moment": "magnetic moment"}

HEADER = """\
<!-- Generated by scripts/generate_docs.py; do not edit. -->
# Kinds and units

Every built-in kind, with its units, named products, quotients, integer powers
and square roots, and the unit each built-in system stores it in. Units are in
their kind's namespace, as in `u.length.nanometer`, and directly on `quantype.u`,
as in `u.nm`, unless a flat name clashes with a kind namespace: namespaces win.
See [unit namespaces](units.md#unit-namespaces) for collision examples.
Dimensions are over quantype's base axes: {axes}.
"""


def _dimensions(exponents: tuple[int, ...]) -> str:
    def term(axis: str, power: int) -> str:
        name = AXES.get(axis, axis)
        return name if power == 1 else f"{name}{str(power).translate(SUPERSCRIPTS)}"

    pairs = list(zip(BASIS, exponents, strict=True))
    numerator = " ".join(term(axis, power) for axis, power in pairs if power > 0)
    denominator = " ".join(term(axis, -power) for axis, power in pairs if power < 0)
    if not denominator:
        return numerator or "dimensionless"
    return f"{numerator or '1'} / {denominator}"


def _kinds() -> str:
    catalogue = builtin_catalogue()
    identifiers: dict[str, list[str]] = {}
    for identifier, name in unit_names(catalogue).items():
        identifiers.setdefault(name, []).append(identifier)
    rows = ["| Kind | Dimensions | Units |", "| --- | --- | --- |"]
    for kind, spec in catalogue.quantities.items():
        units = [
            f"`{name}` ({unit.symbol or name})"
            + "".join(
                f", `{alias}`" for alias in identifiers.get(name, []) if alias != name
            )
            for name, unit in catalogue.units.items()
            if unit.kind == kind
        ]
        rows.append(
            f'| <span id="kind-{kind.lower()}"></span>`{kind}` | '
            f"{_dimensions(spec.dimensions)} | {'; '.join(units)} |"
        )
    return "\n".join(rows)


def _relations() -> str:
    algebra = builtin_catalogue().algebra
    products: set[str] = set()
    quotients: list[str] = []
    for (operation, left, right), result in sorted(algebra.items()):
        if "Dimensionless" in (left, right) and result != "Dimensionless":
            continue  # scaling by a dimensionless value keeps the kind
        if operation == "mul":
            first, second = sorted((left, right))
            products.add(f"`{first}` \N{MULTIPLICATION SIGN} `{second}` = `{result}`")
        elif left != right:
            quotients.append(f"`{left}` / `{right}` = `{result}`")
    return (
        "Products also derive inverse divisions, but explicitly declared divisions "
        "override them. For example, `Pressure` \N{MULTIPLICATION SIGN} "
        "`Volume` = `Energy`, while "
        "`Energy` / `Volume` = `EnergyDensity`, not `Pressure`. Consult the "
        "quotient list below for the actual named results. Any other product or "
        "quotient of two kinds is a product class from `quantype.products`, such as "
        "`LengthTime`; see [the physical model]"
        "(../explanation/physical-model.md#kinds-are-nominal-meanings).\n\n"
        "**Products**\n\n"
        + "\n".join(f"- {line}" for line in sorted(products))
        + "\n\n**Quotients**\n\n"
        + "\n".join(f"- {line}" for line in quotients)
    )


def _powers() -> str:
    catalogue = builtin_catalogue()
    rows = ["| Base kind | Integer exponent | Named result |", "| --- | --- | --- |"]
    for kind in catalogue.quantities:
        exponents = {-1, 2} | {
            exponent for base, exponent in catalogue.powers if base == kind
        }
        for exponent in sorted(exponents):
            result = named_power(catalogue.algebra, catalogue.powers, kind, exponent)
            if result is not None:
                rows.append(f"| `{kind}` | `{exponent}` | `{result}` |")
    roots = [
        "| Input kind | `quantype.numpy.sqrt` result |",
        "| --- | --- |",
    ]
    for (base, exponent), result in catalogue.powers.items():
        if exponent == 2:  # noqa: PLR2004
            roots.append(f"| `{result}` | `{base}` |")
    roots.append("| `Dimensionless` | `Dimensionless` |")
    return (
        "These are the named results of integer `quantity ** exponent`, from "
        "declared powers and the square or reciprocal relations. Exponent `1` "
        "preserves every kind and is omitted. Other integer powers retain "
        "structural kinds; matching dimensions do not infer a named result.\n\n"
        + "\n".join(rows)
        + "\n\n### Square roots\n\n"
        "Named square-root results come from declared square powers, plus "
        "`Dimensionless`; a named cube does not imply a cube-root API. "
        "`quantype.numpy.sqrt` also undoes structural squares (`x ** 2` or "
        "`x * x`), but does not infer roots of arbitrary named kinds from "
        "dimensions. Unsupported kinds raise `TypeError`.\n\n" + "\n".join(roots)
    )


def _systems() -> str:
    names = " | ".join(f"`{system.__name__}`" for system in SYSTEMS)
    rows = [
        f"| Kind | {names} |",
        "| --- |" + " --- |" * len(SYSTEMS),
    ]
    for name, kind in KINDS.items():
        cells = []
        for system in SYSTEMS:
            symbol = system.unit_for(kind).symbol
            # A starred unit is stored outside the base units' coherent products.
            cells.append(f"{symbol}*" if coherence(system, kind) != 1.0 else symbol)
        rows.append(f"| `{name}` | " + " | ".join(cells) + " |")
    return (
        "`.value` is in these units, and `System.unit_for(Kind)` returns them. A star "
        "marks a unit the system sets directly instead of deriving it from its base "
        "units, as LAMMPS does for pressure. Arithmetic that produces or consumes "
        "those kinds rescales.\n\n" + "\n".join(rows)
    )


def render() -> str:
    axes = ", ".join(AXES.get(axis, axis) for axis in BASIS)
    return (
        HEADER.format(axes=axes)
        + "\n## Kinds\n\n"
        + _kinds()
        + "\n\n## Named products and quotients\n\n"
        + _relations()
        + "\n\n## Named integer powers and roots\n\n"
        + _powers()
        + "\n\n## Units by system\n\n"
        + _systems()
        + "\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != source:
            parser.exit(1, f"Stale generated file: {TARGET}\n")
        return
    TARGET.write_text(source)


if __name__ == "__main__":
    main()
