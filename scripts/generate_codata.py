"""Regenerate/check the vendored CODATA table from the NIST tables SciPy bundles.

SciPy ships every CODATA adjustment's ``allascii.txt`` verbatim. Only the
constants quantype uses are extracted, as typed fields with stable names,
because NIST renames some entries between editions. Values NIST prints
truncated (``...``) are exact and are computed from their definitions instead.
"""

import argparse
import math
from collections.abc import Callable
from pathlib import Path

from scipy.constants import (  # pyright: ignore[reportPrivateUsage]
    _codata,  # pyright: ignore[reportPrivateUsage]
)

TARGET = Path(__file__).resolve().parents[1] / "src/quantype/_internal/_codata.py"
EDITIONS = ("2014", "2018", "2022")

# Field -> (SI unit, the NIST entry names that have held it, newest first).
FIELDS: dict[str, tuple[str, tuple[str, ...]]] = {
    "atomic_mass_constant": ("kg", ("atomic mass constant",)),
    "atomic_unit_of_magnetic_dipole_moment": (
        "J/T",
        ("atomic unit of mag. dipole mom.",),
    ),
    "atomic_unit_of_time": ("s", ("atomic unit of time",)),
    "avogadro_constant": ("1/mol", ("Avogadro constant",)),
    "bohr_magneton": ("J/T", ("Bohr magneton",)),
    "bohr_radius": ("m", ("Bohr radius",)),
    "boltzmann_constant": ("J/K", ("Boltzmann constant",)),
    "electron_mass": ("kg", ("electron mass",)),
    "elementary_charge": ("C", ("elementary charge",)),
    "hartree_energy_in_ev": ("eV", ("Hartree energy in eV",)),
    "planck_constant": ("J s", ("Planck constant",)),
    "speed_of_light_in_vacuum": ("m/s", ("speed of light in vacuum",)),
    "vacuum_electric_permittivity": (
        "F/m",
        ("vacuum electric permittivity", "electric constant"),
    ),
}
# Exact values NIST prints truncated, from their definitions.
DEFINITIONS: dict[str, Callable[[dict[str, float]], float]] = {
    # Before 2019 the magnetic constant was exactly 4π 10⁻⁷ N/A².
    "electric constant": lambda values: (
        1 / (4e-7 * math.pi * values["speed_of_light_in_vacuum"] ** 2)
    ),
}
# NIST's fixed-width columns: name, then value, before and after 2018.
COLUMNS = {"2014": (55, 77), "2018": (60, 85), "2022": (60, 85)}

HEADER = '''\
# Generated by scripts/generate_codata.py from the NIST CODATA tables bundled
# with SciPy; do not edit.
"""CODATA recommended values in SI units, for each edition quantype carries.

Field names are stable across editions even where NIST renamed an entry. The
reduced Planck constant is derived as h / 2π wherever it is needed.
"""

from dataclasses import dataclass
from types import MappingProxyType
from typing import Literal

'''


def _table(edition: str) -> dict[str, str]:
    text: str = getattr(_codata, f"txt{edition}")
    name_end, value_end = COLUMNS[edition]
    return {
        line[:name_end].rstrip(): line[name_end:value_end].strip()
        for line in text.splitlines()
        if line.strip()
    }


def _values(edition: str) -> dict[str, float]:
    table = _table(edition)
    values: dict[str, float] = {}
    pending: list[tuple[str, str]] = []
    for field, (_, candidates) in FIELDS.items():
        name = next((name for name in candidates if name in table), None)
        if name is None:
            raise KeyError(f"CODATA {edition} has no entry for {field}")
        raw = table[name]
        if "..." in raw:
            pending.append((field, name))
        else:
            values[field] = float(raw.replace(" ", ""))
    for field, name in pending:
        values[field] = DEFINITIONS[name](values)
    return values


def _literal(value: float) -> str:
    # Spelled as ruff formats float literals, so the file stays stable.
    return repr(value).replace("e+", "e")


def render() -> str:
    editions = ", ".join(f'"{edition}"' for edition in EDITIONS)
    lines = [
        HEADER,
        f"type Edition = Literal[{editions}]\n",
        f"EDITIONS: tuple[Edition, ...] = ({editions})\n\n\n",
        "@dataclass(frozen=True, slots=True, kw_only=True)\n",
        "class Codata:\n",
        '    """One CODATA adjustment: the values quantype defines units from."""\n\n',
        "    edition: Edition\n",
    ]
    lines.extend(
        f"    {field}: float  # {unit}\n" for field, (unit, _) in FIELDS.items()
    )
    for edition in EDITIONS:
        lines.append(f'\n\nCODATA_{edition} = Codata(\n    edition="{edition}",\n')
        lines.extend(
            f"    {field}={_literal(value)},\n"
            for field, value in _values(edition).items()
        )
        lines.append(")\n")
    entries = ", ".join(f'"{edition}": CODATA_{edition}' for edition in EDITIONS)
    lines.append(
        "\nCODATA: MappingProxyType[Edition, Codata] = MappingProxyType(\n"
        f"    {{{entries}}}\n)\n"
    )
    return "".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != source:
            parser.exit(1, f"Stale generated file: {TARGET}\n")
        return
    TARGET.write_text(source)


if __name__ == "__main__":
    main()
