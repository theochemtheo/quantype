"""Generate the nominal API and backend signatures from the semantic registry.

Run ``uv run python scripts/generate.py --check`` in CI. The registry is loaded
directly, so regeneration never requires an already-importable generated package.
"""

# Standalone script; long strings are readable templates for generated signatures.
# ruff: noqa: INP001, E501

from __future__ import annotations

import argparse
import importlib.util
import math
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location(
    "_registry", ROOT / "src/quantype/_registry.py"
)
if SPEC is None or SPEC.loader is None:
    raise RuntimeError("Cannot load the semantic registry")
registry = importlib.util.module_from_spec(SPEC)
sys.modules[SPEC.name] = registry
SPEC.loader.exec_module(registry)
Q = registry.QUANTITIES
U = registry.UNITS
R = registry.RELATIONS
P = registry.POWERS
HEADER = "# Generated by scripts/generate.py; do not edit.\n"


def validate_registry() -> None:
    """Reject inconsistent metadata before emitting any generated file."""
    identifiers: set[str] = set()
    for name, spec in U.items():
        if not name.isidentifier():
            raise ValueError(f"Invalid Python unit identifier: {name}")
        if spec.kind not in Q:
            raise ValueError(f"Unknown kind for unit {name}: {spec.kind}")
        if not math.isfinite(spec.scale) or spec.scale <= 0:
            raise ValueError(f"Invalid scale for unit {name}")
        if not math.isfinite(spec.offset):
            raise ValueError(f"Invalid offset for unit {name}")
        for identifier in (name, *spec.aliases):
            # Parsing aliases may be scientific expressions, not Python names.
            if not identifier.strip() or identifier in identifiers:
                raise ValueError(f"Empty or duplicate unit name: {identifier}")
            identifiers.add(identifier)
    validate_relations()


def validate_relations() -> None:
    """Check canonical units and dimension arithmetic for named operations."""
    for name, spec in Q.items():
        canonical = U[spec.canonical_unit]
        if canonical.kind != name or canonical.scale != 1 or canonical.offset != 0:
            raise ValueError(f"Invalid canonical unit for {name}")
    for (operation, left, right), result in R.items():
        if operation not in {"mul", "div"}:
            raise ValueError(f"Invalid operation: {operation}")
        sign = 1 if operation == "mul" else -1
        dimensions = tuple(
            a + sign * b
            for a, b in zip(Q[left].dimensions, Q[right].dimensions, strict=True)
        )
        if dimensions != Q[result].dimensions:
            raise ValueError(
                f"Dimensionally inconsistent relation: {left} {operation} {right}"
            )
    for (name, power), result in P.items():
        if tuple(d * power for d in Q[name].dimensions) != Q[result].dimensions:
            raise ValueError(f"Dimensionally inconsistent power: {name} ** {power}")


def overloads(signatures: list[str]) -> str:
    if len(signatures) == 1:
        return "    " + signatures[0] + "\n"
    return "".join("    @overload\n    " + sig + "\n" for sig in signatures)


def binary(method: str, name: str, right: str, result: str) -> list[str]:
    """Same-storage, scalar-left, scalar-right broadcasting rules."""
    return [
        f"def {method}(self: {name}[float], other: {right}[W], /) -> {result}[W]: ...",
        f"def {method}(self, other: {right}[float], /) -> {result}[V]: ...",
        f"def {method}(self, other: {right}[V], /) -> {result}[V]: ...",
    ]


def quantity_outputs() -> dict[str, str]:
    kinds = (
        HEADER + '"""Nominal semantic markers and structural expression markers."""\n\n'
    )
    for name in Q:
        kinds += f"class {name}Kind:\n    pass\n\n"
    for name, params in (("Mul", "A, B"), ("Div", "A, B"), ("Pow", "A, N")):
        kinds += f"class {name}[{params}]:\n    pass\n\n"
    imports = "from quantype.core import Quantity\nfrom quantype.kinds import (\n"
    imports += "".join(f"    {name}Kind,\n" for name in Q) + ")\n\n"
    runtime = (
        HEADER
        + '"""Real nominal quantity classes; numerical behavior lives in core."""\n\n'
        + imports
    )
    stubs = (
        HEADER
        + (
            "# Explicit named branches overlap structural fallbacks intentionally.\n"
            "# mypy: disable-error-code=overload-overlap\n"
            "# pyright: reportOverlappingOverload=false\n"
            "from typing import Literal, overload, override\n"
            "import numpy as np\n"
            "import numpy.typing as npt\n"
            "from quantype.kinds import Div, Mul, Pow\n"
        )
        + imports
    )
    for name in Q:
        runtime += (
            f"class {name}[V](Quantity[{name}Kind, V]):\n    _kind = {name!r}\n\n"
        )
        stubs += f"class {name}[V](Quantity[{name}Kind, V]):\n"
        stubs += f"    @classmethod\n    @override\n    def from_canonical[W](cls, value: W) -> {name}[W]: ...\n"
        stubs += f"    @classmethod\n    @override\n    def parse(cls, data: object) -> {name}[float | npt.NDArray[np.float64]]: ...\n"
        stubs += f"    def __neg__(self) -> {name}[V]: ...\n"
        stubs += f"    def __pos__(self) -> {name}[V]: ...\n"
        stubs += f"    def __abs__(self) -> {name}[V]: ...\n"
        for method in ("sum", "mean"):
            stubs += f"    def {method}(self, axis: int | tuple[int, ...] | None = None, *, keepdims: bool = False) -> {name}[V]: ...\n"
        for method in ("__add__", "__sub__"):
            if name == "Temperature":
                sigs = binary(method, name, "TemperatureDifference", name)
                if method == "__sub__":
                    sigs += binary(method, name, name, "TemperatureDifference")
            else:
                sigs = binary(method, name, name, name)
                if name == "TemperatureDifference" and method == "__add__":
                    sigs += binary(method, name, "Temperature", "Temperature")
            # W is method-local; V belongs to the quantity class.
            stubs += overloads(
                [
                    s.replace(f"def {method}(", f"def {method}[W](") if "W" in s else s
                    for s in sigs
                ]
            )
        stubs += multiplicative_stubs(name)
        stubs += f"    def __rmul__(self, other: float, /) -> {name}[V]: ...\n"
        powers = [
            f"def __pow__(self, exponent: Literal[{power}], /) -> {result}[V]: ..."
            for (kind, power), result in P.items()
            if kind == name
        ]
        powers += [
            f"def __pow__[N: int](self, exponent: N, /) -> Quantity[Pow[{name}Kind, N], V]: ..."
        ]
        stubs += overloads(powers) + "\n"
    return {
        "src/quantype/kinds.py": kinds,
        "src/quantype/_generated.py": runtime,
        "src/quantype/_generated.pyi": stubs,
    }


def multiplicative_stubs(name: str) -> str:
    """Emit named relations before general structural-expression fallbacks."""
    stubs = ""
    for op, method, expr in (
        ("mul", "__mul__", "Mul"),
        ("div", "__truediv__", "Div"),
    ):
        sigs = []
        for (operation, left, right), result in R.items():
            if operation == op and left == name:
                sigs += binary(method, name, right, result)
        sigs += [f"def {method}(self, other: float, /) -> {name}[V]: ..."]
        sigs += [
            f"def {method}[K, W](self: {name}[float], other: Quantity[K, W], /) -> Quantity[{expr}[{name}Kind, K], W]: ...",
            f"def {method}[K](self, other: Quantity[K, V], /) -> Quantity[{expr}[{name}Kind, K], V]: ...",
        ]
        stubs += overloads(
            [
                s.replace(f"def {method}(", f"def {method}[W](")
                if "W" in s and "[K" not in s
                else s
                for s in sigs
            ]
        )
    return stubs


def unit_outputs() -> dict[str, str]:
    unit_runtime = (
        HEADER
        + "# Scientific unit symbols intentionally preserve conventional case.\n"
        + "# ruff: noqa: N816\n"
        + "from quantype.core import Unit\nfrom quantype._math import exp, sin, sqrt\n\n"
        + "from quantype.kinds import (\n"
        + "".join(f"    {name}Kind,\n" for name in Q)
        + ")\n\n"
    )
    unit_stub = (
        HEADER
        + (
            "# Scientific unit symbols intentionally preserve conventional case.\n"
            "# ruff: noqa: N816\n"
            "# Scalar normalization intentionally precedes the generic storage case.\n"
            "# mypy: disable-error-code=overload-overlap\n"
            "# pyright: reportOverlappingOverload=false\n"
            "from typing import overload\n"
            "from quantype.core import Unit\n"
            "from quantype._math import exp as exp, sin as sin, sqrt as sqrt\n"
            "from quantype._generated import (\n"
        )
        + "".join(f"    {name},\n" for name in Q)
        + ")\n"
    )
    unit_stub += (
        "from quantype.kinds import (\n"
        + "".join(f"    {name}Kind,\n" for name in Q)
        + ")\n\n"
    )
    for name in Q:
        unit_stub += f"class _{name}Unit(Unit[{name}Kind]):\n"
        for method in ("__call__", "__mul__", "__rmul__"):
            unit_stub += overloads(
                [
                    f"def {method}(self, value: float, /) -> {name}[float]: ...",
                    f"def {method}[V](self, value: V, /) -> {name}[V]: ...",
                ]
            )
        unit_stub += "\n"
    for name, spec in U.items():
        unit_runtime += f"{name} = Unit[{spec.kind}Kind]({name!r}, {spec.kind!r}, {spec.scale!r}, {spec.offset!r}, {spec.symbol!r})\n"
        unit_stub += f"{name}: _{spec.kind}Unit\n"
        for alias in spec.aliases:
            if alias.isidentifier() and alias.isascii():
                unit_runtime += f"{alias} = {name}\n"
                unit_stub += f"{alias}: _{spec.kind}Unit\n"
    exports = ["exp", "sin", "sqrt"]
    for name, spec in U.items():
        exports.append(name)
        exports.extend(
            alias for alias in spec.aliases if alias.isidentifier() and alias.isascii()
        )
    unit_runtime += f"\n__all__ = {sorted(exports)!r}\n"
    return {
        "src/quantype/units.py": unit_runtime,
        "src/quantype/units.pyi": unit_stub,
    }


def adapter_outputs() -> dict[str, str]:
    adapters = {}
    for backend, array in (("ujax", "Array"), ("utorch", "Tensor")):
        source = "jax" if backend == "ujax" else "torch"
        text = HEADER + f"from {source} import {array}\nfrom typing import overload\n"
        if backend == "ujax":
            text += "from collections.abc import Callable\n"
        derivative_kinds = {
            kind
            for (op, left, right), result in R.items()
            if op == "div"
            for kind in (left, right, result)
        }
        text += (
            "from quantype._generated import (\n"
            + "".join(f"    {name},\n" for name in Q if name in derivative_kinds)
            + ")\n\n"
        )
        text += "from quantype.core import Quantity\nfrom quantype.kinds import Div\n\n"
        text += "# mypy: disable-error-code=overload-overlap\n"
        text += "# pyright: reportOverlappingOverload=false\n"
        for (op, output, input_), result in R.items():
            if op != "div":
                continue
            if backend == "ujax":
                text += f"@overload\ndef grad(fun: Callable[[{input_}[Array]], {output}[Array]]) -> Callable[[{input_}[Array]], {result}[Array]]: ...\n"
            else:
                text += f"@overload\ndef grad(output: {output}[Tensor], inputs: {input_}[Tensor], *, create_graph: bool = False, retain_graph: bool | None = None) -> {result}[Tensor]: ...\n"
        if backend == "ujax":
            text += "@overload\ndef grad[I, O](fun: Callable[[Quantity[I, Array]], Quantity[O, Array]]) -> Callable[[Quantity[I, Array]], Quantity[Div[O, I], Array]]: ...\n"
        else:
            text += "@overload\ndef grad[I, O](output: Quantity[O, Tensor], inputs: Quantity[I, Tensor], *, create_graph: bool = False, retain_graph: bool | None = None) -> Quantity[Div[O, I], Tensor]: ...\n"
        if backend == "ujax":
            for (op, output, input_), result in R.items():
                second = R.get(("div", result, input_))
                if op == "div" and second is not None:
                    text += f"@overload\ndef hessian(fun: Callable[[{input_}[Array]], {output}[Array]]) -> Callable[[{input_}[Array]], {second}[Array]]: ...\n"
            text += "@overload\ndef hessian[I, O](fun: Callable[[Quantity[I, Array]], Quantity[O, Array]]) -> Callable[[Quantity[I, Array]], Quantity[Div[Div[O, I], I], Array]]: ...\n"
            text += "def jit[**P, T](fun: Callable[P, T]) -> Callable[P, T]: ...\n"
            text += "def vmap[**P, T](fun: Callable[P, T], in_axes: int | None = 0, out_axes: int = 0) -> Callable[P, T]: ...\n"
        adapters[f"src/quantype/{backend}.pyi"] = text
    return adapters


def outputs() -> dict[str, str]:
    return {**quantity_outputs(), **unit_outputs(), **adapter_outputs()}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    validate_registry()
    stale = []
    uv = shutil.which("uv")
    if uv is None:
        parser.exit(1, "uv is required to format generated files\n")
    for relative, source in outputs().items():
        # Use the project's pinned formatter, not a second formatting policy.
        fixed = subprocess.run(  # noqa: S603 -- trusted generated source, no shell
            [
                uv,
                "run",
                "ruff",
                "check",
                "--fix",
                "--select",
                "I",
                "--stdin-filename",
                relative,
                "-",
            ],
            input=source,
            capture_output=True,
            text=True,
            check=True,
            cwd=ROOT,
        ).stdout
        content = subprocess.run(  # noqa: S603 -- trusted generated source, no shell
            [uv, "run", "ruff", "format", "--stdin-filename", relative, "-"],
            input=fixed,
            capture_output=True,
            text=True,
            check=True,
            cwd=ROOT,
        ).stdout
        path = ROOT / relative
        if not path.exists() or path.read_text() != content:
            stale.append(relative)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    if args.check and stale:
        parser.exit(1, "Stale generated files:\n" + "\n".join(stale) + "\n")


if __name__ == "__main__":
    main()
