"""Pure renderers for nominal quantities, unit namespaces, and autodiff stubs.

Quantity stubs are generic over storage ``V`` and unit system ``S``. ``S`` is a
defaulted ``typing_extensions.TypeVar`` (PEP 696), so ``Length[float]`` means
``Length[float, Atomistic]``. It passes through every overload unchanged, and is
invariant, so operands from different systems match no overload.
"""

from __future__ import annotations

import keyword
from typing import TYPE_CHECKING

from quantype.catalogue import (
    _namespace_name as namespace_name,  # pyright: ignore[reportPrivateUsage]
)

if TYPE_CHECKING:
    from quantype.catalogue import Catalogue

# Source templates keep individual generated signatures on one line.
# ruff: noqa: E501

HEADER = "# Generated by quantype.codegen; do not edit.\n"
OVERLAPS = "# mypy: disable-error-code=overload-overlap\n# pyright: reportOverlappingOverload=false\n"
# Named operators and structural-only base operators have disjoint self types.
# Checkers still compare their return types as ordinary subclass overrides.
# Class-level parameters. Method-level parameters use PEP 695 syntax.
TYPE_VARIABLES = (
    "# Public parameter names read better in diagnostics than private ones.\n"
    "# ruff: noqa: PYI001\n"
    "from typing_extensions import TypeVar\n"
    "from quantype.systems import Atomistic, UnitSystem\n"
    "V = TypeVar('V')\n"
    "S = TypeVar('S', bound=UnitSystem, default=Atomistic)\n"
)
QUANTITY_OVERRIDES = (
    "# Named operators and structural-only base operators have disjoint self types.\n"
    "# mypy: disable-error-code=override\n"
    "# pyright: reportIncompatibleMethodOverride=false\n"
)


def overloads(
    signatures: list[str], indent: str = "    ", *, overrides: bool = False
) -> str:
    decorator = indent + "@override\n" if overrides else ""
    if len(signatures) == 1:
        return decorator + indent + signatures[0] + "\n"
    return "".join(
        indent
        + "@overload\n"
        + (decorator if index == 0 else "")
        + indent
        + signature
        + "\n"
        for index, signature in enumerate(signatures)
    )


def binary(method: str, name: str, right: str, result: str) -> list[str]:
    return [
        f"def {method}(self: {name}[float, S], other: {right}[W, S], /) -> {result}[W, S]: ...",
        f"def {method}(self, other: {right}[float, S], /) -> {result}[V, S]: ...",
        f"def {method}(self, other: {right}[V, S], /) -> {result}[V, S]: ...",
    ]


def method_overloads(method: str, signatures: list[str]) -> str:
    return overloads(
        [
            signature.replace(f"def {method}(", f"def {method}[W](")
            if "[W, S]" in signature and "[K" not in signature
            else signature
            for signature in signatures
        ],
        overrides=True,
    )


def additive_stubs(name: str) -> str:
    text = ""
    for method in ("__add__", "__sub__"):
        if name == "Temperature":
            signatures = binary(method, name, "TemperatureDifference", name)
            if method == "__sub__":
                signatures += binary(method, name, name, "TemperatureDifference")
        else:
            signatures = binary(method, name, name, name)
            if name == "TemperatureDifference" and method == "__add__":
                signatures += binary(method, name, "Temperature", "Temperature")
        text += method_overloads(method, signatures)
    return text


def multiplicative_stubs(name: str, catalogue: Catalogue) -> str:
    relations = catalogue.algebra
    text = ""
    for op, method, expression in (
        ("mul", "__mul__", "Mul"),
        ("div", "__truediv__", "Div"),
    ):
        signatures: list[str] = []
        for (operation, left, right), result in relations.items():
            if operation == op and left == name:
                signatures += binary(method, name, right, result)
        signatures += [
            f"def {method}(self, other: float, /) -> {name}[V, S]: ...",
            f"def {method}[K, W](self: {name}[float, S], other: Quantity[K, W, S], /) -> Quantity[{expression}[{name}Kind, K], W, S]: ...",
            f"def {method}[K](self, other: Quantity[K, float, S], /) -> Quantity[{expression}[{name}Kind, K], V, S]: ...",
            f"def {method}[K](self, other: Quantity[K, V, S], /) -> Quantity[{expression}[{name}Kind, K], V, S]: ...",
        ]
        text += method_overloads(method, signatures)
    return text


def quantity_methods(name: str, catalogue: Catalogue) -> str:
    text = f"    @classmethod\n    @override\n    def define_unit(cls, name: str, *, reference: Unit[{name}Kind], scale: float = 1.0, offset: float = 0.0, symbol: str | None = None) -> _units._{name}Unit: ...\n"
    text += f"    @classmethod\n    @override\n    def from_value[W](cls, value: W) -> {name}[W, S]: ...\n"
    text += f"    @classmethod\n    @override\n    def parse(cls, data: object, *, units: tuple[Unit[Any], ...] = ()) -> {name}[float | npt.NDArray[np.float64], S]: ...\n"
    text += f"    @override\n    def to_system[T: UnitSystem](self, system: type[T]) -> {name}[V, T]: ...\n"
    text += additive_stubs(name)
    for method in ("__neg__", "__abs__"):
        text += f"    @override\n    def {method}(self) -> {name}[V, S]: ...\n"
    # Absolute temperatures scale and multiply, but a sum of them is meaningless.
    if name != "Temperature":
        text += f"    @override\n    def sum(self, axis: int | tuple[int, ...] | None = None, *, keepdims: bool = False) -> {name}[V, S]: ...\n"
    text += multiplicative_stubs(name, catalogue)
    text += (
        f"    @override\n    def __rmul__(self, other: float, /) -> {name}[V, S]: ...\n"
    )
    reciprocal = catalogue.algebra.get(("div", "Dimensionless", name))
    result = (
        f"{reciprocal}[V, S]"
        if reciprocal is not None
        else f"Quantity[Div[DimensionlessKind, {name}Kind], V, S]"
    )
    # A named inverse refines the structural-only base return type. Ty and
    # Pyrefly also compare these mutually exclusive self types as overrides.
    suppression = (
        "  # pyrefly: ignore[bad-override]  # ty: ignore[invalid-method-override]"
        if reciprocal is not None
        else ""
    )
    text += f"    @override\n    def __rtruediv__(self, other: float, /) -> {result}: ...{suppression}\n"
    powers = [
        f"def __pow__(self, exponent: Literal[{power}], /) -> {result}[V, S]: ..."
        for (kind, power), result in catalogue.powers.items()
        if kind == name
    ]
    powers += [
        f"def __pow__[N: int](self, exponent: N, /) -> Quantity[Pow[{name}Kind, N], V, S]: ..."
    ]
    return text + overloads(powers, overrides=True)


def constant_stub(name: str, catalogue: Catalogue) -> str:
    """A kind's constant: system-free, adopting each quantity operand's system.

    A reflected operand is typed structurally (see ``_Operand`` in core.pyi), and
    a constant on the left handles products of constants.
    """
    own = f"_{name}Constant"
    scalar_types = "float | np.floating[Any] | np.integer[Any]"
    text = f"\nclass {own}(Constant[{name}Kind]):\n"
    text += f"    @override\n    def to_system[T: UnitSystem](self, system: type[T]) -> {name}[float, T]: ...\n"
    text += f"    @override\n    def to(self, unit: Unit[{name}Kind]) -> {name}[float]: ...\n"
    algebra = catalogue.algebra
    for method, op, expression, reflected in (
        ("__mul__", "mul", "Mul", False),
        ("__rmul__", "mul", "Mul", True),
        ("__truediv__", "div", "Div", False),
        ("__rtruediv__", "div", "Div", True),
    ):
        signatures = [
            f"def {method}[W, T: UnitSystem](self, other: {other}[W, T], /) -> {result}[W, T]: ..."
            for (operation, left, right), result in algebra.items()
            if operation == op
            for other in [left if reflected else right]
            if (right if reflected else left) == name
        ]
        # A named reciprocal refines the base's structural return type, as the
        # quantity classes' __rtruediv__ does; checkers compare it as an override.
        suppression = ""
        if method == "__rtruediv__":
            reciprocal = algebra.get(("div", "Dimensionless", name))
            scalar = (
                f"_{reciprocal}Constant"
                if reciprocal is not None
                else f"Constant[Div[DimensionlessKind, {name}Kind]]"
            )
            if reciprocal is not None:
                suppression = "  # ty: ignore[invalid-method-override]"
        else:
            scalar = own
        pair = f"L, {name}Kind" if reflected else f"{name}Kind, L"
        signatures += [
            f"def {method}(self, other: {scalar_types}, /) -> {scalar}: ...",
            f"def {method}[L, W, T: UnitSystem](self, other: _Operand[L, W, T], /) -> Quantity[{expression}[{pair}], W, T]: ...",
        ]
        if not reflected:
            signatures.append(
                f"def {method}[L](self, other: Constant[L], /) -> Constant[{expression}[{pair}]]: ..."
            )
        # ty reports an overloaded override at its last signature; pyrefly at
        # its first, which a wrapped signature leaves no room to annotate.
        signatures[-1] += suppression
        block = overloads(signatures, overrides=True)
        if suppression:
            first = block.index("    def ")
            block = (
                block[:first] + "    # pyrefly: ignore[bad-override]\n" + block[first:]
            )
        text += block
    return text


def structural_quantity_stub() -> str:
    """A generated base carries its own dimensionless marker through trees."""
    text = "K = TypeVar('K')\n"
    text += "type _StructuralQuantity[A, B, X, Y: UnitSystem] = Quantity[Mul[A, B], X, Y] | Quantity[Div[A, B], X, Y] | Quantity[Pow[A, B], X, Y]\n"
    text += "class Quantity(_BaseQuantity[K, V, S]):\n"
    for method in ("__add__", "__sub__"):
        text += overloads(
            [
                f"def {method}[A, B, W](self: _StructuralQuantity[A, B, float, S], other: Quantity[K, W, S], /) -> Quantity[K, W, S]: ...",
                f"def {method}[A, B](self: _StructuralQuantity[A, B, V, S], other: Quantity[K, float, S], /) -> Quantity[K, V, S]: ...",
                f"def {method}[A, B](self: _StructuralQuantity[A, B, V, S], other: Quantity[K, V, S], /) -> Quantity[K, V, S]: ...",
            ],
            overrides=True,
        )
    for method, expression in (("__mul__", "Mul"), ("__truediv__", "Div")):
        text += overloads(
            [
                f"def {method}[A, B](self: _StructuralQuantity[A, B, V, S], other: float, /) -> Quantity[K, V, S]: ...",
                f"def {method}[A, B, L, W](self: _StructuralQuantity[A, B, float, S], other: Quantity[L, W, S], /) -> Quantity[{expression}[K, L], W, S]: ...",
                f"def {method}[A, B, L](self: _StructuralQuantity[A, B, V, S], other: Quantity[L, float, S], /) -> Quantity[{expression}[K, L], V, S]: ...",
                f"def {method}[A, B, L](self: _StructuralQuantity[A, B, V, S], other: Quantity[L, V, S], /) -> Quantity[{expression}[K, L], V, S]: ...",
            ],
            overrides=True,
        )
    text += "    @override\n    def __rmul__[A, B](self: _StructuralQuantity[A, B, V, S], other: float, /) -> Quantity[K, V, S]: ...\n"
    # The shared base necessarily uses the builtin marker. This refinement is
    # nominal, not a widening; each catalogue has its own structural base.
    text += "    @override\n    def __rtruediv__[A, B](self: _StructuralQuantity[A, B, V, S], other: float, /) -> Quantity[Div[DimensionlessKind, K], V, S]: ...  # pyrefly: ignore[bad-override]  # ty: ignore[invalid-method-override]\n"
    text += "    @override\n    def __pow__[A, B, N: int](self: _StructuralQuantity[A, B, V, S], exponent: N, /) -> Quantity[Pow[K, N], V, S]: ...\n"
    for method in ("__neg__", "__abs__"):
        text += f"    @override\n    def {method}[A, B](self: _StructuralQuantity[A, B, V, S]) -> Quantity[K, V, S]: ...\n"
    text += "    @override\n    def sum[A, B](self: _StructuralQuantity[A, B, V, S], axis: int | tuple[int, ...] | None = None, *, keepdims: bool = False) -> Quantity[K, V, S]: ...\n"
    return text


def quantity_outputs(catalogue: Catalogue, package: str) -> dict[str, str]:
    kinds = HEADER + '"""Nominal and structural semantic markers."""\n\n'
    kinds += "from quantype._internal._kind_types import Div, Mul, Pow\n\n"
    exports = ["Div", "Mul", "Pow"]
    exports += [f"{name}Kind" for name in catalogue.quantities]
    kinds += f"__all__ = {sorted(exports)!r}\n\n"
    for name in catalogue.quantities:
        kinds += f"class {name}Kind:\n    pass\n\n"
    markers = (
        f"from {package}.kinds import ("
        + ", ".join(f"{name}Kind" for name in catalogue.quantities)
        + ")\n"
    )
    # Constant classes register themselves by kind; nothing names them here.
    runtime = HEADER + "# pyright: reportUnusedClass=false\n" + markers
    runtime += (
        "from quantype.systems import UnitSystem\nfrom quantype.core import Constant\n"
    )
    if package == "quantype":
        runtime += "from quantype.core import Quantity\n"
    else:
        runtime += "from quantype.core import Quantity as _BaseQuantity\n"
        runtime += f"from {package}._catalogue import runtime\n"
        runtime += "class Quantity[K, V, S: UnitSystem](_BaseQuantity[K, V, S]):\n    _catalogue_dimensionless = runtime.kinds['Dimensionless']\n"
    stub = (
        HEADER + OVERLAPS + QUANTITY_OVERRIDES + "# pyright: reportPrivateUsage=false\n"
    )
    stub += "from typing import Any, Literal, overload, override\nimport numpy as np\nimport numpy.typing as npt\nfrom quantype.core import Constant, Unit, _Operand\n"
    stub += (
        "from quantype.core import Quantity\n"
        if package == "quantype"
        else "from quantype.core import Quantity as _BaseQuantity\n"
    )
    stub += (
        markers
        + f"from {package}.kinds import Div, Mul, Pow\nfrom {package} import units as _units\n"
        + TYPE_VARIABLES
    )
    if package != "quantype":
        stub += structural_quantity_stub()
    for name in catalogue.quantities:
        runtime += f"\nclass {name}[V, S: UnitSystem](Quantity[{name}Kind, V, S]):\n    _kind = {name!r}\n"
        if package != "quantype":
            runtime += f"    _semantic = runtime.kinds[{name!r}]\n"
        stub += f"\nclass {name}(Quantity[{name}Kind, V, S]):\n" + quantity_methods(
            name, catalogue
        )
    for name in catalogue.quantities:
        runtime += f"\nclass _{name}Constant(Constant[{name}Kind]):\n    _constant_kind = {name!r}\n"
        if package != "quantype":
            runtime += f"    _constant_semantic = runtime.kinds[{name!r}]\n"
        stub += constant_stub(name, catalogue)
    return {"kinds.py": kinds, "_generated.py": runtime, "_generated.pyi": stub}


def unit_names(catalogue: Catalogue) -> dict[str, str]:
    return {
        identifier: name
        for name, spec in catalogue.units.items()
        for identifier in (name, *spec.aliases)
        if identifier.isidentifier()
        and identifier.isascii()
        and not keyword.iskeyword(identifier)
    }


def namespace_outputs(catalogue: Catalogue) -> tuple[str, str, list[str]]:
    runtime, stub = "", ""
    exports: list[str] = []
    for kind in catalogue.quantities:
        namespace = namespace_name(kind)
        runtime += f"\nclass _{kind}Namespace:\n"
        stub += f"\nclass _{kind}Namespace:\n"
        for name, spec in catalogue.units.items():
            if spec.kind == kind:
                runtime += f"    @property\n    def {name}(self) -> Unit[{kind}Kind]:\n        return cast('Unit[{kind}Kind]', get_unit({name!r}))\n"
                stub += f"    @property\n    def {name}(self) -> _{kind}Unit: ...\n"
        runtime += f"\n{namespace} = _{kind}Namespace()\n"
        stub += f"\n{namespace}: _{kind}Namespace\n"
        exports.append(namespace)
    return runtime, stub, exports


def unit_outputs(catalogue: Catalogue, package: str) -> dict[str, str]:
    namespaces = {namespace_name(kind) for kind in catalogue.quantities}
    names = {
        name: unit
        for name, unit in unit_names(catalogue).items()
        if name not in namespaces
    }
    markers = (
        f"from {package}.kinds import ("
        + ", ".join(f"{name}Kind" for name in catalogue.quantities)
        + ")\n"
    )
    runtime = (
        HEADER
        + "# Scientific unit names preserve conventional case; flat names load lazily.\n# ruff: noqa: N802, F822, E501\n# pyright: reportUnsupportedDunderAll=false\n"
    )
    runtime += (
        "from typing import Any, cast\nfrom quantype.core import Unit\n" + markers
    )
    runtime += (
        "from quantype.core import get_unit\n"
        if package == "quantype"
        else f"from {package}._catalogue import runtime\nget_unit = runtime.get_unit\n"
    )
    math_module = (
        "quantype._internal._math" if package == "quantype" else f"{package}._math"
    )
    runtime += f"from {math_module} import exp, sin, sqrt\n"
    stub = (
        HEADER
        + OVERLAPS
        + "# ruff: noqa: N816, N802\nfrom typing import Any, overload\nimport numpy as np\nfrom quantype.core import Unit\n"
        + markers
    )
    stub += f"from {math_module} import exp as exp, sin as sin, sqrt as sqrt\n"
    stub += (
        f"from {package}._generated import (" + ", ".join(catalogue.quantities) + ")\n"
    )
    for name in catalogue.quantities:
        stub += f"\nclass _{name}Unit(Unit[{name}Kind]):\n"
        for method in ("__call__", "__mul__", "__rmul__"):
            stub += overloads(
                [
                    f"def {method}[S: np.floating[Any]](self, value: S, /) -> {name}[S]: ...",
                    f"def {method}(self, value: float, /) -> {name}[float]: ...",
                    f"def {method}[V](self, value: V, /) -> {name}[V]: ...",
                ]
            )
    for identifier, name in names.items():
        stub += f"{identifier}: _{catalogue.units[name].kind}Unit\n"
    runtime += f"\n_NAMES = {names!r}\n"
    runtime += "\ndef __getattr__(name: str) -> Unit[Any]:\n    if name not in _NAMES:\n        raise AttributeError(name)\n    unit = get_unit(_NAMES[name])\n    globals()[name] = unit\n    return unit\n"
    namespace_runtime, namespace_stub, namespace_names = namespace_outputs(catalogue)
    exports = sorted(["exp", "sin", "sqrt", *names, *namespace_names])
    return {
        "units.py": runtime + namespace_runtime + f"\n__all__ = {exports!r}\n",
        "units.pyi": stub + namespace_stub + f"\n__all__ = {exports!r}\n",
    }


def gradient_signatures(catalogue: Catalogue, backend: str, array: str) -> list[str]:
    signatures: list[str] = []
    for (operation, output, input_), result in catalogue.algebra.items():
        if operation != "div":
            continue
        if backend == "ujax":
            signatures.append(
                f"def grad[S: UnitSystem](function: Callable[[{input_}[Array, S]], {output}[Array, S]]) -> Callable[[{input_}[Array, S]], {result}[Array, S]]: ..."
            )
        else:
            signatures.append(
                f"def grad[S: UnitSystem](output: {output}[Tensor, S], inputs: {input_}[Tensor, S], *, create_graph: bool = False, retain_graph: bool | None = None) -> {result}[Tensor, S]: ..."
            )
    if backend == "ujax":
        signatures.append(
            "def grad[I, O, S: UnitSystem](function: Callable[[Quantity[I, Array, S]], Quantity[O, Array, S]]) -> Callable[[Quantity[I, Array, S]], Quantity[Div[O, I], Array, S]]: ..."
        )
    else:
        signatures.append(
            f"def grad[I, O, S: UnitSystem](output: Quantity[O, {array}, S], inputs: Quantity[I, {array}, S], *, create_graph: bool = False, retain_graph: bool | None = None) -> Quantity[Div[O, I], {array}, S]: ..."
        )
    return signatures


def hessian_signatures(catalogue: Catalogue) -> list[str]:
    signatures: list[str] = []
    for (operation, output, input_), result in catalogue.algebra.items():
        second = catalogue.algebra.get(("div", result, input_))
        if operation == "div" and second is not None:
            signatures.append(
                f"def hessian[S: UnitSystem](function: Callable[[{input_}[Array, S]], {output}[Array, S]]) -> Callable[[{input_}[Array, S]], {second}[Array, S]]: ..."
            )
    signatures.append(
        "def hessian[I, O, S: UnitSystem](function: Callable[[Quantity[I, Array, S]], Quantity[O, Array, S]]) -> Callable[[Quantity[I, Array, S]], Quantity[Div[Div[O, I], I], Array, S]]: ..."
    )
    return signatures


def adapter_outputs(catalogue: Catalogue, package: str) -> dict[str, str]:
    outputs: dict[str, str] = {}
    for backend, source, array in (
        ("ujax", "jax", "Array"),
        ("utorch", "torch", "Tensor"),
    ):
        text = (
            HEADER
            + OVERLAPS
            + f"from {source} import {array}\nfrom typing import overload\n"
            + "from quantype.systems import UnitSystem\n"
        )
        if backend == "ujax":
            text += "from collections.abc import Callable\n"
        if package == "quantype" and backend == "ujax":
            text += "from typing import Any\n"
        derivative_kinds = {
            kind
            for (op, left, right), result in catalogue.algebra.items()
            if op == "div"
            for kind in (left, right, result)
        }
        if derivative_kinds:
            text += (
                f"from {package}._generated import ("
                + ", ".join(
                    name for name in catalogue.quantities if name in derivative_kinds
                )
                + ")\n"
            )
        quantity_module = "quantype.core" if package == "quantype" else package
        text += (
            f"from {quantity_module} import Quantity\nfrom {package}.kinds import Div\n"
        )
        text += overloads(gradient_signatures(catalogue, backend, array), indent="")
        if backend == "ujax":
            text += overloads(hessian_signatures(catalogue), indent="")
            text += "def jit[**P, T](fun: Callable[P, T]) -> Callable[P, T]: ...\n"
            text += "def vmap[**P, T](fun: Callable[P, T], in_axes: int | None = 0, out_axes: int = 0) -> Callable[P, T]: ...\n"
        if package == "quantype" and backend == "ujax":
            text += "def _register_quantity(cls: type[Quantity[Any, Any, Any]]) -> None: ...\n"
        outputs[f"{backend}.pyi"] = text
    return outputs


def outputs(catalogue: Catalogue, package: str) -> dict[str, str]:
    return {
        **quantity_outputs(catalogue, package),
        **unit_outputs(catalogue, package),
        **adapter_outputs(catalogue, package),
    }
