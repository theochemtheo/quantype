"""Minify the private stub modules, which type checkers read and people don't.

They are most of the installed package. Minifying keeps every token that
carries meaning, so checkers see the same module: it drops optional
whitespace and comments other than checker directives, and imports
``overload`` and ``override`` under short names, as they decorate nearly every
signature. Names checkers print in diagnostics are left alone.
"""

from __future__ import annotations

import io
import tokenize
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Iterator

# Comments a checker reads, and the notice that the file is generated.
_KEPT_COMMENTS = (
    "# mypy:",
    "# pyright:",
    "# pyrefly:",
    "# ty:",
    "# type:",
    "# Generated by",
)
_DECORATORS = {"overload": "_o", "override": "_v"}
_OPENING = {"(", "[", "{"}
_CLOSING = {")", "]", "}"}


def _lines(source: str) -> Iterator[tuple[int, list[tokenize.TokenInfo]]]:
    """Each logical line's indentation level and tokens, with kept comments."""
    tokens: list[tokenize.TokenInfo] = []
    indent = brackets = 0
    for token in tokenize.generate_tokens(io.StringIO(source).readline):
        if token.type == tokenize.INDENT:
            indent += 1
        elif token.type == tokenize.DEDENT:
            indent -= 1
        elif token.type == tokenize.NEWLINE or (
            token.type == tokenize.NL and not brackets
        ):
            if tokens:
                yield indent, tokens
            tokens = []
        elif token.type == tokenize.COMMENT:
            if token.string.startswith(_KEPT_COMMENTS):
                tokens.append(token)
        elif token.type not in {tokenize.NL, tokenize.ENDMARKER}:
            brackets += (token.string in _OPENING) - (token.string in _CLOSING)
            tokens.append(token)


def _spelled(tokens: list[tokenize.TokenInfo]) -> str:
    """A logical line's tokens, spaced only where two words meet."""
    words = {tokenize.NAME, tokenize.NUMBER}
    typing_import = [token.string for token in tokens[:3]] == [
        "from",
        "typing",
        "import",
    ]
    text = ""
    for index, token in enumerate(tokens):
        string = token.string
        previous = tokens[index - 1] if index else None
        if token.type == tokenize.COMMENT:
            string = f"  {string}" if text else string
        elif previous is not None and previous.string == "@":
            string = _DECORATORS.get(string, string)
        elif typing_import and string in _DECORATORS:
            string = f"{string} as {_DECORATORS[string]}"
        if previous is not None and previous.type in words and token.type in words:
            text += " "
        text += string
    return text


def minify(source: str) -> str:
    return "".join(
        f"{' ' * indent}{_spelled(tokens)}\n" for indent, tokens in _lines(source)
    )
